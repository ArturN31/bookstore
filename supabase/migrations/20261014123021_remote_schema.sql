CREATE OR REPLACE FUNCTION public.increment_book_stock(p_book_id uuid, p_quantity integer)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
BEGIN
    UPDATE public.books
    SET 
        stock_quantity = stock_quantity + p_quantity,
        sales_count = GREATEST(0, COALESCE(sales_count, 0) - p_quantity),
        updated_at = (now() AT TIME ZONE 'utc'::text)
    WHERE id = p_book_id;
END;
$function$
;

CREATE OR REPLACE FUNCTION public.process_order_transaction(p_payload jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    v_user_id uuid;
    v_total_amount numeric;
    v_subtotal numeric;
    v_discount_amount numeric;
    v_shipping_cost numeric;
    v_tax_amount numeric;
    v_shipping_method_id text;
    v_shipping_method_name text;
    v_payment_method text;
    v_discount_id uuid;
    v_payment_intent_id text;
    v_order_id uuid;
    v_item jsonb;
    v_book_id uuid;
    v_quantity smallint;
    v_price numeric;
    v_current_stock smallint;
    v_is_active boolean;
    
    -- Discount validation variables
    v_discount_active boolean;
    v_discount_start timestamp without time zone;
    v_discount_end timestamp without time zone;
    v_discount_min_subtotal numeric;
    v_discount_usage_limit integer;
    v_discount_times_used integer;
    v_discount_uses_per_user integer;
    v_user_redemption_count integer;
    
    v_shipping_address jsonb;
BEGIN
    -- Extract financial breakdown and metadata from the payload
    v_user_id := (p_payload->>'user_id')::uuid;
    v_total_amount := (p_payload->>'total_amount')::numeric;
    v_subtotal := COALESCE((p_payload->>'subtotal')::numeric, 0.00);
    v_discount_amount := COALESCE((p_payload->>'discount_amount')::numeric, 0.00);
    v_shipping_cost := COALESCE((p_payload->>'shipping_cost')::numeric, 0.00);
    v_tax_amount := COALESCE((p_payload->>'tax_amount')::numeric, 0.00);
    v_shipping_method_id := COALESCE(p_payload->>'shipping_method_id', 'royal_mail_standard');
    v_shipping_method_name := COALESCE(p_payload->>'shipping_method_name', 'Royal Mail Standard');
    v_payment_method := p_payload->>'payment_method';
    v_payment_intent_id := p_payload->>'payment_intent_id';
    v_shipping_address := p_payload->'shipping_address';

    IF p_payload->>'discount_id' IS NOT NULL AND p_payload->>'discount_id' <> '' THEN
        v_discount_id := (p_payload->>'discount_id')::uuid;
    ELSE
        v_discount_id := NULL;
    END IF;

    -- Basic guard clauses
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'CHECKOUT_LOGIN_REQUIRED';
    END IF;

    IF v_total_amount IS NULL OR v_total_amount <= 0 THEN
        RAISE EXCEPTION 'ORDER_CREATION_FAILED';
    END IF;

    IF v_payment_intent_id IS NULL OR v_payment_intent_id = '' THEN
        RAISE EXCEPTION 'PAYMENT_PROCESSING_FAILED';
    END IF;

    IF jsonb_array_length(p_payload->'items') = 0 THEN
        RAISE EXCEPTION 'EMPTY_CART_CHECKOUT';
    END IF;

    -- 1. Lock and validate stock for all items atomically
    FOR v_item IN SELECT * FROM jsonb_array_elements(p_payload->'items')
    LOOP
        v_book_id := (v_item->>'book_id')::uuid;
        v_quantity := (v_item->>'quantity')::smallint;

        IF v_quantity <= 0 THEN
            RAISE EXCEPTION 'ORDER_CREATION_FAILED';
        END IF;

        SELECT stock_quantity, is_active 
        INTO v_current_stock, v_is_active
        FROM public.books
        WHERE id = v_book_id
        FOR UPDATE;

        IF NOT FOUND OR NOT v_is_active OR v_current_stock < v_quantity THEN
            RAISE EXCEPTION 'INSUFFICIENT_STOCK';
        END IF;
    END LOOP;

    -- 2. Atomically lock and revalidate discount constraints (dates, limits, minimum spend, per-user caps)
    IF v_discount_id IS NOT NULL THEN
        SELECT is_active, start_date, end_date, minimum_subtotal, usage_limit, times_used, uses_per_user
        INTO v_discount_active, v_discount_start, v_discount_end, v_discount_min_subtotal, v_discount_usage_limit, v_discount_times_used, v_discount_uses_per_user
        FROM public.discounts
        WHERE id = v_discount_id
        FOR UPDATE;

        IF NOT FOUND OR NOT v_discount_active THEN
            RAISE EXCEPTION 'DISCOUNT_NOT_ACTIVE';
        END IF;

        IF v_discount_start IS NOT NULL AND clock_timestamp() < v_discount_start THEN
            RAISE EXCEPTION 'DISCOUNT_NOT_ACTIVE';
        END IF;

        IF v_discount_end IS NOT NULL AND clock_timestamp() > v_discount_end THEN
            RAISE EXCEPTION 'EXPIRED_DISCOUNT_CODE';
        END IF;

        IF v_discount_min_subtotal IS NOT NULL AND v_subtotal < v_discount_min_subtotal THEN
            RAISE EXCEPTION 'INVALID_DISCOUNT_CODE';
        END IF;

        IF v_discount_usage_limit IS NOT NULL AND v_discount_times_used >= v_discount_usage_limit THEN
            RAISE EXCEPTION 'EXPIRED_DISCOUNT_CODE';
        END IF;

        IF v_discount_uses_per_user IS NOT NULL THEN
            SELECT count(*)
            INTO v_user_redemption_count
            FROM public.order_discounts od
            JOIN public.orders o ON o.id = od.order_id
            WHERE od.discount_id = v_discount_id
              AND o.user_id = v_user_id
              AND o.status NOT IN ('cancelled', 'failed');

            IF v_user_redemption_count >= v_discount_uses_per_user THEN
                RAISE EXCEPTION 'EXPIRED_DISCOUNT_CODE';
            END IF;
        END IF;
    END IF;

    -- 3. Insert order record with full financial ledger
    INSERT INTO public.orders (
        user_id,
        subtotal,
        discount_amount,
        shipping_cost,
        tax_amount,
        total_amount,
        shipping_method_id,
        shipping_method_name,
        status,
        payment_method,
        stripe_payment_intent_id
    ) VALUES (
        v_user_id,
        v_subtotal,
        v_discount_amount,
        v_shipping_cost,
        v_tax_amount,
        v_total_amount,
        v_shipping_method_id,
        v_shipping_method_name,
        'pending',
        v_payment_method,
        v_payment_intent_id
    ) RETURNING id INTO v_order_id;

    -- 4. Insert immutable shipping address record
    IF v_shipping_address IS NOT NULL THEN
        INSERT INTO public.order_addresses (
            order_id,
            address_type,
            first_name,
            last_name,
            street_address,
            city,
            postcode,
            country,
            phone_number
        ) VALUES (
            v_order_id,
            'shipping',
            COALESCE(v_shipping_address->>'firstName', ''),
            COALESCE(v_shipping_address->>'lastName', ''),
            COALESCE(v_shipping_address->>'streetAddress', ''),
            COALESCE(v_shipping_address->>'city', ''),
            COALESCE(v_shipping_address->>'postcode', ''),
            COALESCE(v_shipping_address->>'country', 'United Kingdom'),
            COALESCE(v_shipping_address->>'phoneNumber', '')
        );
    END IF;

    -- 5. Insert order items & reduce book stock quantities
    FOR v_item IN SELECT * FROM jsonb_array_elements(p_payload->'items')
    LOOP
        v_book_id := (v_item->>'book_id')::uuid;
        v_quantity := (v_item->>'quantity')::smallint;
        v_price := (v_item->>'price')::numeric;

        INSERT INTO public.order_items (order_id, book_id, quantity, price)
        VALUES (v_order_id, v_book_id, v_quantity, v_price);

        UPDATE public.books
        SET 
            stock_quantity = stock_quantity - v_quantity,
            sales_count = COALESCE(sales_count, 0) + v_quantity,
            updated_at = (now() AT TIME ZONE 'utc'::text)
        WHERE id = v_book_id;
    END LOOP;

    -- 6. Attach discount to order and increment global usage counter atomically
    IF v_discount_id IS NOT NULL THEN
        INSERT INTO public.order_discounts (order_id, discount_id)
        VALUES (v_order_id, v_discount_id);

        UPDATE public.discounts
        SET 
            times_used = times_used + 1,
            updated_at = (now() AT TIME ZONE 'utc'::text)
        WHERE id = v_discount_id;
    END IF;

    RETURN jsonb_build_object('success', true, 'order_id', v_order_id);
END;
$function$
;

