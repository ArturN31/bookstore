create or replace view "public"."books_with_stats" as  SELECT b.id,
    b.created_at,
    b.updated_at,
    b.title,
    b.author,
    b.genre,
    b.publisher,
    b.publication_date,
    b.price,
    b.description,
    b.format,
    b.page_count,
    b.image_url,
    b.stock_quantity,
    b.is_active,
    b.sales_count,
    COALESCE(avg(r.rating), (0)::numeric) AS avg_rating,
    count(r.id) AS review_count
   FROM (public.books b
     LEFT JOIN public.book_reviews r ON ((b.id = r.book_id)))
  GROUP BY b.id;


